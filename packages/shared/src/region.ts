export function resolveSupportedRegion(value: string | null | undefined, cityCode?: string | null) {
  const normalized = (value || '').replace(/\s+/g, '').replace(/市$/, '');
  return (
    supportedRegions.find((item) => item.cityCode === cityCode) ||
    supportedRegions.find((item) =>
      item.aliases.some((alias) => alias.replace(/\s+/g, '').replace(/市$/, '') === normalized),
    ) ||
    null
  );
}

export function getSupportedProvinces() {
  return supportedRegions
    .reduce<Array<{ provinceCode: string; provinceName: string; cities: SupportedRegion[] }>>(
      (result, item) => {
        const province = result.find((row) => row.provinceCode === item.provinceCode);
        if (province) province.cities.push(item);
        else result.push({ provinceCode: item.provinceCode, provinceName: item.provinceName, cities: [item] });
        return result;
      },
      [],
    );
}
